#!/usr/bin/env python3
"""Generate ``feature_tree.yaml`` — a structural map of the codebase.

Walks ``src/`` and emits a hierarchical YAML mirroring the directory and module
layout under four roots: ``core``, ``gui``, ``plugins`` and ``utilities``.

Disabled items are excluded to match the module loader: anything whose name
starts with an underscore (see ``src/core/managers/modules.py``), plus
``base.py``. Each ``.py`` module becomes a leaf; its value is the class-level
``display_name``/``default_name`` label when present, otherwise ``null``.

This is a pure filesystem + ``ast`` walk — it never imports project modules, so
it is deterministic and free of side effects.

Usage
-----
    python scripts/generate_feature_tree.py            # write feature_tree.yaml
    python scripts/generate_feature_tree.py --check    # exit 1 if it would change
"""

from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

import yaml


REPO_ROOT = Path(__file__).resolve().parent.parent
SRC = REPO_ROOT / "src"
OUTPUT = REPO_ROOT / "feature_tree.yaml"

# Top-level YAML key -> directory name under src/.
ROOTS = {"core": "core", "gui": "gui", "plugins": "plugins", "utilities": "utils"}

# Class attributes carrying a short human-readable label.
LABEL_ATTRS = ("display_name", "default_name")

# Directories that hold runtime artifacts rather than source features.
SKIP_DIRS = {"baked"}

HEADER = (
    "# AgentPilot Feature Tree\n"
    "# Auto-generated by scripts/generate_feature_tree.py — do not edit by hand.\n"
    "# Structure-only mirror of src/ (underscore-prefixed disabled items excluded).\n"
)


def should_skip(name: str, is_dir: bool) -> bool:
    """Return whether a filesystem entry is excluded from the tree.

    Mirrors the loader's skip convention: underscore-prefixed names (which also
    covers ``__pycache__`` and ``__init__.py``) and ``base`` modules.
    """
    if name.startswith("_"):
        return True
    if name == ("base" if is_dir else "base.py"):
        return True
    if not is_dir and not name.endswith(".py"):
        return True
    if is_dir and name in SKIP_DIRS:
        return True
    return False


def extract_label(py_path: Path) -> str | None:
    """Return the first class-level label string in a module, without importing.

    Parses the file and scans class-scope assignments for a target named in
    ``LABEL_ATTRS`` bound to a string literal.
    """
    try:
        tree = ast.parse(py_path.read_text(encoding="utf-8"))
    except (SyntaxError, UnicodeDecodeError):
        return None

    for node in ast.walk(tree):
        if not isinstance(node, ast.ClassDef):
            continue
        for stmt in node.body:
            if not isinstance(stmt, ast.Assign):
                continue
            value = stmt.value
            if not (isinstance(value, ast.Constant) and isinstance(value.value, str)):
                continue
            for target in stmt.targets:
                if isinstance(target, ast.Name) and target.id in LABEL_ATTRS:
                    return value.value
    return None


def walk_dir(dir_path: Path) -> dict:
    """Build a nested dict mirroring a directory's modules and subpackages.

    Empty branches are pruned, so asset directories without modules disappear.
    """
    tree: dict = {}
    for entry in sorted(dir_path.iterdir()):
        if should_skip(entry.name, entry.is_dir()):
            continue
        if entry.is_dir():
            subtree = walk_dir(entry)
            if subtree:
                tree[entry.name] = subtree
        else:
            tree[entry.stem] = extract_label(entry)
    return tree


def build_tree() -> dict:
    """Return the full feature tree keyed by the four top-level roots."""
    return {key: walk_dir(SRC / subdir) for key, subdir in ROOTS.items()}


def count_leaves(tree: dict) -> int:
    """Return the number of module leaves in the tree."""
    total = 0
    for value in tree.values():
        total += count_leaves(value) if isinstance(value, dict) else 1
    return total


def render(tree: dict) -> str:
    """Serialize the tree to the full YAML document, header included."""
    body = yaml.safe_dump(
        tree,
        sort_keys=True,
        default_flow_style=False,
        indent=2,
        allow_unicode=True,
        width=4096,
    )
    return HEADER + body


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if feature_tree.yaml is out of date instead of writing it",
    )
    args = parser.parse_args()

    tree = build_tree()
    content = render(tree)

    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            print(f"{OUTPUT.name} is out of date — run generate_feature_tree.py")
            return 1
        print(f"{OUTPUT.name} is up to date")
        return 0

    OUTPUT.write_text(content, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(REPO_ROOT)} ({count_leaves(tree)} modules)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
